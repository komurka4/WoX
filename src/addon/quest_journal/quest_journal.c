/* quest_journal (Phase 247 add-on, NOT original behavior): the Quests
 * dialog's numbered rows, the quest items' description window and the
 * places of quests and notes (include/xeen/addon/quest_journal.h). Drawn on a
 * copy of the displayed page; DS is read, never written. Self-contained: no
 * bug fix; the world map itself is add-on world_map's. */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "xeen/addon/quest_journal.h"
#include "xeen/ds_globals.h"
#include "xeen/sprites.h"
#include "xeen/text_window.h"
/* The driver's window rectangles (generated from XEEN.DAT, as presentation.c uses them): the dialog's list is
 * window 1Eh. */
#include "../../graphics/window_table.inc"

int xeen_quest_journal_on;

/* Generated by tools/make_tables.py (a developer step): see that file. */
typedef struct {
    int8_t quest;            /* the Current Quests entry whose bit selects AFTER; -1: one text */
    const char *before, *after;
} qj_item_text;
typedef struct {
    uint8_t kind;            /* 0 none, 1 a cell, 2 a place (an entrance, a town), 3 an NPC */
    uint8_t world, x, y;     /* the world map's cell (y from the south) */
    const char *label;
} qj_target;
#include "descriptions.inc"
#include "targets.inc"

enum { LIST_WINDOW = 0x1e, BORDER = 8, ROWS = 9, ITEMS_MODE = 0, QUESTS_MODE = 1, NOTES_MODE = 2 };

static struct {
    int started;
    xeen_text_window font;
    int listed, mode, numbered;                 /* a list is shown; how many of its rows are numbered */
    int id[ROWS], digit[ROWS];                  /* each shown row's number (-1 none) and key 1..9 (0 none) */
    int top[ROWS], bottom[ROWS];                /* each row's pixel rows (bottom exclusive) */
    int left[ROWS], right[ROWS], line[ROWS];    /* each number's cell: x from, x to, its line's height */
    int exact;                                  /* every number took a bullet's place: only the cells change */
    char text[4096];                            /* the list's text with the numbers (4E38C) */
    int item_open;
    char item[1024];                            /* the description window's text */
    uint8_t page[64000], scratch[64000];
    const char *capture; unsigned captured;     /* developer evidence: XEEN_QUEST_JOURNAL_CAPTURE=DIR */
    int log;                                    /* developer evidence: XEEN_QUEST_JOURNAL_LOG (stderr) */
} qj;

int xeen_quest_journal_start(const void *sprite_archives)
{
    const xeen_sprite_archives *a = sprite_archives;
    unsigned i;
    xeen_quest_journal_stop();
    if (!a)
        return 0;
    for (i = 0; i < 2u && !qj.font.loaded; ++i)
        if (a->cc[i])
            (void)xeen_text_window_load(&qj.font, a->cc[i]);
    if (!qj.font.loaded)
        return 0;
    qj.capture = getenv("XEEN_QUEST_JOURNAL_CAPTURE"); /* developer evidence only */
    qj.log = getenv("XEEN_QUEST_JOURNAL_LOG") != NULL;  /* developer evidence only */
    qj.started = 1;
    xeen_quest_journal_on = 1;
    return 1;
}
void xeen_quest_journal_stop(void)
{
    xeen_quest_journal_on = 0;
    memset(&qj, 0, sizeof qj);
}

/* ------------------------------------------------------------ the list */
/** Nonzero when MODE's entry ID can be opened (an item's text; a quest's or a note's place while MAPS). */
static int actionable(int mode, int id, int maps)
{
    if (id < 0)
        return 0;
    if (mode == ITEMS_MODE)
        return id < 85 && qj_item_texts[id].before != NULL;
    if (!maps)
        return 0;
    if (mode == QUESTS_MODE)
        return id < 56 && qj_quest_targets[id].kind != 0;
    return id < 128 && qj_note_targets[id].kind != 0;
}
/** Appends S to the text at *AT (truncated at the buffer's end). */
static void put(size_t *at, const char *s)
{
    size_t n = strlen(s);
    if (*at + n >= sizeof qj.text)
        n = sizeof qj.text - 1u - *at;
    memcpy(qj.text + *at, s, n);
    *at += n;
    qj.text[*at] = 0;
}
/* DS:703A's row prefix: the bullet " * " in colour 04, then the default colour. */
static const char bullet[] = "\x0c" "04 * \x0c" "d";

/** Each of the ROWS shown rows' entry (IDS[i], -1 past N) and its key: the actionable rows numbered 1, 2, .. in
 * order (qj.digit 0 for the others); qj.numbered counts them. */
static void number_rows(int mode, const int *ids, unsigned n, int maps)
{
    unsigned i;
    for (i = 0; i < ROWS; ++i) {
        qj.id[i] = i < n ? ids[i] : -1;
        qj.digit[i] = i < n && actionable(mode, ids[i], maps) ? ++qj.numbered : 0;
    }
}
/** A numbered row's number, appended at *AT in the key colour (37) in place of its bullet " * " (colour 04): the
 * format's bullet just before the row (removed: *START, the row's start, moves back to it), else the entry's own
 * (skipped: the returned entry starts after it), else the number goes before the entry and the line's layout
 * changes (qj.exact 0: the whole window is drawn). Returns the entry text to append after the number. */
static const char *put_number(size_t *at, size_t *start, const char *entry, int digit)
{
    char num[24];
    snprintf(num, sizeof num, "\x0c" "37 %d \x0c" "d", digit);
    if (*at >= sizeof bullet - 1u && !memcmp(qj.text + *at - (sizeof bullet - 1u), bullet, sizeof bullet - 1u)) {
        *at -= sizeof bullet - 1u;              /* the format's bullet */
        qj.text[*at] = 0;
        *start = *at;
    } else if (!strncmp(entry, bullet, sizeof bullet - 1u)) {
        entry += sizeof bullet - 1u;            /* the entry's bullet */
    } else {
        snprintf(num, sizeof num, "\x0c" "37%d\x0c" "d ", digit);
        qj.exact = 0;                           /* the line's layout changes: the whole window is drawn */
    }
    put(at, num);
    return entry;
}
/** qj.text: FORMAT with each %s replaced by the next of the N ROWS (a numbered row's number first, put_number), so
 * the layout is the original's; START, NUMEND and END each row's offsets (its start, after its number, after its
 * entry). Returns the rows composed (at most N: a %s past them ends the text). */
static unsigned compose_rows(const char *format, const char *const *rows, unsigned n, size_t *start, size_t *numend,
                             size_t *end)
{
    size_t at = 0;
    unsigned row = 0;
    const char *f;
    qj.text[0] = 0;
    qj.exact = 1;
    for (f = format; *f; ++f) {
        char one[2] = {*f, 0};
        const char *entry;
        if (f[0] != '%' || f[1] != 's') {
            put(&at, one);
            continue;
        }
        ++f;
        if (row >= n)
            break;
        entry = rows[row] ? rows[row] : "";
        start[row] = at;
        if (qj.digit[row])
            entry = put_number(&at, &start[row], entry, qj.digit[row]);
        numend[row] = at;
        put(&at, entry);
        end[row++] = at;
    }
    return row;
}
/** Each of the first COUNT rows' pixel rows (qj.top, bottom) and its number's cell (qj.left, right, line): the list
 * window's layout run in pieces over qj.text (its state carries between them, as one call's); the other rows 0. */
static void measure_rows(unsigned count, const size_t *start, const size_t *numend, const size_t *end)
{
    xeen_text_layout s;
    unsigned i;
    xeen_text_layout_init(&s, window_rects[LIST_WINDOW], BORDER);
    for (i = 0; i < count; ++i) {
        (void)xeen_text_layout_run(&s, &qj.font, NULL, (const uint8_t *)qj.text, start[i], i ? end[i - 1] : 0);
        qj.top[i] = s.y;
        qj.left[i] = s.x;
        (void)xeen_text_layout_run(&s, &qj.font, NULL, (const uint8_t *)qj.text, numend[i], start[i]);
        qj.right[i] = s.x;
        qj.line[i] = s.reduced ? 9 : 10;
        (void)xeen_text_layout_run(&s, &qj.font, NULL, (const uint8_t *)qj.text, end[i], numend[i]);
        qj.bottom[i] = s.y + (s.reduced ? 9 : 10);
    }
    for (; i < ROWS; ++i)
        qj.top[i] = qj.bottom[i] = 0;
}
void xeen_quest_journal_listed(int mode, const char *format, const char *const *rows, const int *ids,
                               unsigned n, int maps)
{
    size_t start[ROWS], end[ROWS], numend[ROWS];
    unsigned i;
    qj.listed = qj.numbered = 0;
    qj.item_open = 0;
    if (!qj.started || !format || !rows || !ids || n > ROWS)
        return;
    qj.mode = mode;
    number_rows(mode, ids, n, maps);
    if (!qj.numbered)
        return;                                  /* the original list, untouched */
    measure_rows(compose_rows(format, rows, n, start, numend, end), start, numend, end);
    qj.listed = 1;
    if (qj.log) {
        fprintf(stderr, "quest_journal list mode=%d numbered=%d", mode, qj.numbered);
        for (i = 0; i < n; ++i)
            fprintf(stderr, " %d:%d@%d-%d", qj.digit[i], qj.id[i], qj.top[i], qj.bottom[i]);
        fprintf(stderr, "\n");
    }
}
void xeen_quest_journal_ended(void) { qj.listed = qj.numbered = qj.item_open = 0; }

int xeen_quest_journal_pick(uint16_t key, int click, uint16_t px, uint16_t py)
{
    const uint16_t *w = window_rects[LIST_WINDOW];
    unsigned i;
    if (!qj.listed || !qj.numbered)
        return -1;
    for (i = 0; i < ROWS; ++i) {
        if (!qj.digit[i])
            continue;
        if (key >= '1' && key <= '9' && qj.digit[i] == key - '0')
            return qj.id[i];
        if (!key && click && px >= w[0] && px < w[0] + w[2] && py >= qj.top[i] && py < qj.bottom[i])
            return qj.id[i];
    }
    return -1;
}

/* ------------------------------------------------- the description window */
int xeen_quest_journal_open_item(unsigned item, const char *name, const uint8_t *ds)
{
    const qj_item_text *t;
    const char *body;
    if (!qj.started || item >= 85u || !qj_item_texts[item].before || !ds)
        return 0;
    t = &qj_item_texts[item];
    body = t->before;
    if (t->quest >= 0) {                         /* Current Quests entry q: bit q + 1 of F06F (3E58D) */
        unsigned bit = (unsigned)t->quest + 1u;
        if (ds[(uint16_t)(XEEN_DS_QUEST_FLAGS + (bit >> 3))] & (0x80u >> (bit & 7u)))
            body = t->after;
    }
    snprintf(qj.item, sizeof qj.item, "\x03" "c%s\x03l\n\n%s", name ? name : "", body);
    qj.item_open = 1;
    if (qj.log)
        fprintf(stderr, "quest_journal item %u %s (%s)\n", item, name ? name : "", body == t->before ? "before" : "after");
    return 1;
}
int xeen_quest_journal_item_open(void) { return qj.item_open; }
void xeen_quest_journal_close_item(void)
{
    if (qj.log && qj.item_open)
        fprintf(stderr, "quest_journal item closed\n");
    qj.item_open = 0;
}
int xeen_quest_journal_in_window(uint16_t px, uint16_t py)
{
    const uint16_t *w = window_rects[LIST_WINDOW];
    return px >= w[0] && px < w[0] + w[2] && py >= w[1] && py < w[1] + w[3];
}

/* ------------------------------------------------------------ the places */
int xeen_quest_journal_target(int mode, unsigned id, xeen_world_map_place *mark, const char **label)
{
    const qj_target *t = mode == QUESTS_MODE && id < 56u  ? &qj_quest_targets[id]
                         : mode == NOTES_MODE && id < 128u ? &qj_note_targets[id]
                                                          : NULL;
    if (!t || !t->kind || !mark)
        return 0;
    mark->world = t->world;
    mark->x = t->x;
    mark->y = t->y;
    mark->dir = 0;
    if (label)
        *label = t->label;
    if (qj.log)
        fprintf(stderr, "quest_journal place mode=%d id=%u world=%d cell=%d,%d %s\n", mode, id, mark->world, mark->x,
                mark->y, t->label);
    return 1;
}

/* ------------------------------------------------------------ drawing */
/** Developer evidence: the drawn page as qj-NNNN.bin (at most 2000). */
static void capture(const uint8_t *page)
{
    char name[1100];
    FILE *f;
    if (!qj.capture || qj.captured >= 2000u)
        return;
    snprintf(name, sizeof name, "%s/qj-%04u.bin", qj.capture, qj.captured++);
    if ((f = fopen(name, "wb"))) {
        (void)fwrite(page, 1, 64000, f);
        fclose(f);
    }
}
const uint8_t *xeen_quest_journal_page(const uint8_t *page)
{
    const uint16_t *w = window_rects[LIST_WINDOW];
    uint16_t win[4] = {w[0], w[1], w[2], w[3]}, foot[4] = {w[0], (uint16_t)(w[1] + w[3] - 25u), w[2], 16};
    static const char footer[] = "\x03" "c\x0c" "04Press space to close\x0c" "d"; /* owner: white (04) */
    xeen_text_layout s;
    if (!qj.started || !page || !qj.listed || (!qj.numbered && !qj.item_open))
        return page;
    memcpy(qj.page, page, sizeof qj.page);
    (void)xeen_text_frame(qj.page, sizeof qj.page, win);
    xeen_text_layout_init(&s, win, BORDER);
    if (qj.item_open) {
        (void)xeen_text_layout_run(&s, &qj.font, qj.page, (const uint8_t *)qj.item, strlen(qj.item) + 1u, 0);
        xeen_text_layout_init(&s, foot, BORDER);
        (void)xeen_text_layout_run(&s, &qj.font, qj.page, (const uint8_t *)footer, sizeof footer, 0);
    } else if (!qj.exact) {
        (void)xeen_text_layout_run(&s, &qj.font, qj.page, (const uint8_t *)qj.text, strlen(qj.text) + 1u, 0);
    } else {
        /* The list drawn on a scratch page; only the number cells reach the shown page, the rest stays the
         * game's own (its text, and the mouse pointer the presentation drew into it). */
        unsigned i;
        int y;
        memcpy(qj.page, page, sizeof qj.page);
        memcpy(qj.scratch, page, sizeof qj.scratch);
        (void)xeen_text_frame(qj.scratch, sizeof qj.scratch, win);
        (void)xeen_text_layout_run(&s, &qj.font, qj.scratch, (const uint8_t *)qj.text, strlen(qj.text) + 1u, 0);
        for (i = 0; i < ROWS; ++i)
            if (qj.digit[i] && qj.right[i] > qj.left[i] && qj.left[i] >= 0 && qj.right[i] <= 320)
                for (y = qj.top[i]; y < qj.top[i] + qj.line[i] && y < 200; ++y)
                    if (y >= 0)
                        memcpy(qj.page + y * 320 + qj.left[i], qj.scratch + y * 320 + qj.left[i],
                               (size_t)(qj.right[i] - qj.left[i]));
    }
    capture(qj.page);
    return qj.page;
}
