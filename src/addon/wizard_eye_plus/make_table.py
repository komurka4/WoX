#!/usr/bin/env python3
"""Add-on wizard_eye_plus (Phase 318, NOT original behavior): generates sky_maps.inc, the maps whose minimap uses the
wizard_eye_plus.sky style, from the original state archives (dos/XEEN.CUR and dos/DARK.CUR; never XEEN.DAT).
Developer tool, run by hand:

    python3 -B src/addon/wizard_eye_plus/make_table.py > src/addon/wizard_eye_plus/sky_maps.inc
    python3 -B src/addon/wizard_eye_plus/make_table.py --check     # the checked-in file is current

The owner's rule: a map is a sky map when the party can fall there. The original's step falls (17264, kind
C0EA[surface] by CS:02BA) are the surface classes 10 (sky.srf: 172AA, always) and 13 (cloud.srf: 172D8, unless
Levitate is on). A party can stand on any cell but a sky one (a cloud cell carries it while it levitates). So a map
is a sky map when one of its fall cells can be entered from a cell the party can stand on:
- the surface of a cell: outdoors the low nibble of its map word, indoors its flags byte & 7 (1C783), classified
  by the maze's 16-byte table at .dat +798 (C0EA: the party map's, also for the quadrants of a composite indoor map,
  e.g. map 26 = mazes 26, 103, 104, 105);
- a step: indoors only through a wall nibble of 0 on the side faced (17B85; facing N/E/S/W read the shifts 12, 8, 4,
  0, north being y + 1), outdoors always; across a maze's edge into the maze its .dat +770 links name (N, E, S, W).
Walled-in sky is left out: the towers' outsides (Ellinger's, the Western, Southern, Eastern and Northern Towers,
Darkstone, Dragon Tower) and Castle Kalindra's and Blackfang's are surrounded by walls. A map is listed by its own
number (ED99), a quadrant maze by its parent's.
Operation 52 (the scripted fall: the Troll Holes' pits on Darkside's outdoor maps, the towers' trapdoors) is not a
sky fall and is not counted (owner's request: the maps that contain sky)."""
import struct
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'tools/xeen_scenario'))
import xeen_data as X  # noqa: E402

FALL = (10, 13)                                     # sky.srf, cloud.srf
STEPS = ((0, 1, 12), (1, 0, 8), (0, -1, 4), (-1, 0, 0))  # N E S W: dx, dy, the current cell's wall shift
WORLDS = ((0, 'XEEN.CUR', 'XEEN.CC', 'xeen'), (1, 'DARK.CUR', 'DARK.CC', 'dark'))


def load(cur):
    raw = (ROOT / 'dos' / cur).read_bytes()
    mazes = {}
    for mp in range(256):
        dat = X.member(raw, 'maze%c%03u.dat' % ('x' if mp > 99 else '0', mp), True)
        if dat:
            mazes[mp] = dat
    return mazes


def outdoor(dat):
    return bool(struct.unpack_from('<H', dat, 780)[0] & 0x8000)


def parents(mazes):
    """A composite indoor map's quadrant mazes (>= 100) -> the map (< 100) whose header names them N or E (or N's E)."""
    parent = {}
    for mp, dat in mazes.items():
        n, e = struct.unpack_from('<2H', dat, 770)
        if mp < 100 and not outdoor(dat):
            for q in (n, e) + ((struct.unpack_from('<H', mazes[n], 772)[0],) if n in mazes else ()):
                if q and q != mp and q >= 100:
                    parent.setdefault(q, mp)
    return parent


def sky_maps(mazes):
    parent = parents(mazes)

    def kind(mp, x, y):
        dat = mazes[mp]
        i = y * 16 + x
        surface = (dat[2 * i] & 15) if outdoor(dat) else (dat[512 + i] & 7)
        return mazes[parent.get(mp, mp)][798 + surface]

    found = {}
    for mp, dat in mazes.items():
        links = struct.unpack_from('<4H', dat, 770)
        for y in range(16):
            for x in range(16):
                if kind(mp, x, y) == 10:
                    continue  # a sky cell is fallen through: nobody stands there
                wall = struct.unpack_from('<H', dat, 2 * (y * 16 + x))[0]
                for k, (dx, dy, shift) in enumerate(STEPS):
                    if not outdoor(dat) and (wall >> shift) & 15:
                        continue
                    nx, ny, to = x + dx, y + dy, mp
                    if not (0 <= nx < 16 and 0 <= ny < 16):
                        to = links[k]
                        if to not in mazes:
                            continue
                        nx, ny = nx % 16, ny % 16
                    if kind(to, nx, ny) in FALL:
                        found.setdefault(parent.get(mp, mp), (mp, x, y, 'NESW'[k]))
    return found


def name(world, mp):
    cc, prefix = WORLDS[world][2], WORLDS[world][3]
    t = X.member((ROOT / 'dos' / cc).read_bytes(), '%s%c%03u.txt' % (prefix, 'x' if mp > 99 else '0', mp), False)
    return t.split(b'\0')[0].decode('latin-1') if t else ''


def table():
    out = ['/* Generated by src/addon/wizard_eye_plus/make_table.py from dos/XEEN.CUR and dos/DARK.CUR (do not edit):',
           ' * {world (96E2/94), map (ED99)} of every map with a fall cell the party can step onto (sky.srf or cloud.srf);',
           ' * the comment names the first such step found (maze, x, y, the side) and the map\'s name where the CC has one. */']
    for world, cur, _, _ in WORLDS:
        for mp, (maze, x, y, side) in sorted(sky_maps(load(cur)).items()):
            label = name(world, mp)
            out.append('{%u, %u}, /* maze %u (%u,%u) %s%s */' % (world, mp, maze, x, y, side,
                                                                ' ' + label if label else ''))
    return '\n'.join(out) + '\n'


def main(argv):
    text = table()
    if '--check' in argv:
        have = (Path(__file__).resolve().parent / 'sky_maps.inc').read_text()
        if have != text:
            print('sky_maps.inc is stale: rerun make_table.py', file=sys.stderr)
            return 1
        print('sky_maps.inc: current (%d maps)' % (text.count('\n') - 3))
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
