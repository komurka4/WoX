/* ------------------------------------------------------------ resources */
/** Extracts NAME from the CC archive A (NULL when absent). */
static uint8_t *resource(const xeen_archive *a, const char *name, size_t *n)
{
    xeen_resource_info i;
    uint8_t *b;
    if (xeen_archive_find_name(a, name, &i) != XR_OK ||
        !(b = malloc(i.size ? i.size : 1u)))
        return NULL;
    if (xeen_archive_extract(a, XR_BANK_ASSETS_XOR35, &i, b, i.size, n) != XR_OK) {
        free(b);
        return NULL;
    }
    return b;
}
/** The mm4.pal entry nearest to (R, G, B) (0..63; green weighs most). */
static uint8_t nearest(int r, int g, int b)
{
    long best = -1;
    unsigned k, at = 0;
    for (k = 0; k < 256u; ++k) {
        long dr = r - wm.pal[3 * k], dg = g - wm.pal[3 * k + 1], db = b - wm.pal[3 * k + 2];
        long d = 3 * dr * dr + 4 * dg * dg + 2 * db * db;
        if (best < 0 || d < best) { best = d; at = k; }
    }
    return (uint8_t)at;
}
/** The mean colour of the full image's block X0..X1 x Y0..Y1 (exclusive), as a palette entry. */
static uint8_t block(int x0, int x1, int y0, int y1)
{
    int x, y, r = 0, g = 0, b = 0, n = 0;
    for (y = y0; y < y1; ++y)
        for (x = x0; x < x1; ++x) {
            const uint8_t *p = wm.pal + 3 * wm.full[y][x];
            r += p[0]; g += p[1]; b += p[2]; ++n;
        }
    return nearest(r / n, g / n, b / n);
}

/* ---------------------------------------------------------- the images */
/* The M map's view on the page (1DA2D): its top left corner; it is 160 x 128 (16 x 16 cells). */
enum { MAP_VIEW_X = 0x50, MAP_VIEW_Y = 0x26 };
/**
 * Draws sector ID (1..24) into the full image: its record (from the state
 * archive, or RECORD when given: the live DS copy) as the cache's slot 0 of
 * the scratch state S, the M map pass at origin (7, 8) (columns x 0..15,
 * rows y 15..0: the whole sector) and its outdoor.til draws.
 */
static int draw_sector(xeen_movement *s, const xeen_archive *state, unsigned id, const uint8_t *record,
                       const uint8_t *til, size_t til_size)
{
    static xeen_map_draws d;
    static xeen_navigation_cache c;
    static uint8_t page[64000];
    xeen_patch_inputs patch = {(uint8_t)wm.world, 0};
    xeen_map_view v = {0, 7, 8, 0, 0, 0};
    unsigned col = (id - 1u) / 4u, row = (id - 1u) % 4u, i, y;
    memset(s, 0, sizeof *s);
    s->ds[XEEN_DS_WORLD] = (uint8_t)wm.world;
    if (xeen_cache_prepare(state, XR_BANK_STATE, (uint16_t)id, patch, &c) != XR_OK)
        return 0;
    if (record)
        memcpy(c.records[0].bytes, record, sizeof c.records[0].bytes);
    if (xeen_cache_commit(&c, s) != XR_OK || !xeen_read16(s, XEEN_DS_OUTDOORS))
        return 0;                                 /* not an outdoor map */
    xeen_write16(s, XEEN_DS_MAP_SLOT, 0);         /* the slot xeen_map_begin's search finds */
    xeen_write16(s, XEEN_DS_MINIMAP_TILES, 1);    /* outdoor.til (the only handle drawn) */
    xeen_write16(s, XEEN_DS_GLOBAL_SPRITES, 2);
    if (xeen_scene_map(s, &v, &d) != XEEN_OK)
        return 0;
    memset(page, BACKGROUND, sizeof page);
    for (i = 0; i < d.count; ++i)
        if (d.draws[i].handle == 1u)
            (void)xeen_raster_frame(til, til_size, d.draws[i].frame, page, sizeof page, (int16_t)d.draws[i].x,
                                    (int16_t)d.draws[i].y, 0, 0);
    for (y = 0; y < 16u * CELL_H; ++y)
        memcpy(&wm.full[row * 16u * CELL_H + y][col * 16u * CELL_W], page + (MAP_VIEW_Y + y) * 320u + MAP_VIEW_X,
               16u * CELL_W);
    return 1;
}
/** Builds the three images of world wm.world from STATE and ASSETS (that world's CC); LIVE, when it is that
 *  world's running game, gives the loaded outdoor maps' newer records. 0 when a sector or a resource is missing. */
static int build(const xeen_archive *state, const xeen_archive *assets, const xeen_movement *m)
{
    xeen_movement *s = malloc(sizeof *s);
    uint8_t *pal, *til;
    size_t n, til_size;
    unsigned id, k, live;
    int x, y, ok = 1;
    if (!s)
        return 0;
    pal = resource(assets, "mm4.pal", &n);
    til = resource(assets, "outdoor.til", &til_size);
    free(wm.arrow);
    wm.arrow = resource(assets, "global.icn", &wm.arrow_size);
    if (!pal || n < 768u || !til || !wm.arrow || xeen_text_window_load(&wm.text, assets) != XR_OK)
        ok = 0;
    if (ok)
        memcpy(wm.pal, pal, 768);
    free(pal);
    /* The loaded outdoor maps (F608: the cache holds the current map and its
     * outdoor neighbours) are drawn from DS: their stepped-on bits are newer
     * than the archive's until the map is left. */
    live = m && xeen_read16(m, XEEN_DS_OUTDOORS) != 0u;
    memset(wm.full, BACKGROUND, (size_t)WORLD_W * WORLD_H);
    for (id = 1; ok && id <= 24u; ++id) {
        const uint8_t *record = NULL;
        for (k = 0; live && k < 9u; ++k)
            if (xeen_read16(m, (uint16_t)(XEEN_DS_MAP_SLOT_IDS + 2u * k)) == id)
                record = m->ds + XEEN_DS_MAP_DATA + k * XEEN_MAP_RECORD_BYTES;
        ok = draw_sector(s, state, id, record, til, til_size);
    }
    free(til);
    free(s);
    if (!ok)
        return 0;
    for (y = 0; y < WORLD_H / 2; ++y)
        for (x = 0; x < WORLD_W / 2; ++x)
            wm.half[y][x] = block(2 * x, 2 * x + 2, 2 * y, 2 * y + 2);
    for (y = 0; y < FIT_H; ++y)
        for (x = 0; x < FIT_W; ++x)
            wm.fit[y][x] = block(x * WORLD_W / FIT_W, (x + 1) * WORLD_W / FIT_W, y * WORLD_H / FIT_H,
                                 (y + 1) * WORLD_H / FIT_H);
    return 1;
}

/* ----------------------------------------------------------- the view */
static int zoom_w(int z) { return z == ZOOM_FULL ? WORLD_W : z == ZOOM_HALF ? WORLD_W / 2 : FIT_W; }
static int zoom_h(int z) { return z == ZOOM_FULL ? WORLD_H : z == ZOOM_HALF ? WORLD_H / 2 : FIT_H; }
/** Full-size pixels per shown pixel (100%, 50%). */
static int scale(int z) { return z == ZOOM_HALF ? 2 : 1; }
/** Keeps the viewport inside the zoom's image (the whole world is not panned). The origin is kept in
 *  full-size pixels at every zoom, so zooming out and back in at one point restores the view exactly. */
static void clamp(void)
{
    int mx = (zoom_w(wm.zoom) - VIEW_W) * scale(wm.zoom), my = (zoom_h(wm.zoom) - VIEW_H) * scale(wm.zoom);
    if (wm.zoom == ZOOM_WORLD) { wm.ox = wm.oy = 0; return; }
    wm.ox = wm.ox > mx ? mx : wm.ox; wm.ox = wm.ox < 0 ? 0 : wm.ox;
    wm.oy = wm.oy > my ? my : wm.oy; wm.oy = wm.oy < 0 ? 0 : wm.oy;
}
/** The full image's point under viewport point (AX, AY) at zoom Z (origin OX, OY). */
static void to_full(int z, int ax, int ay, int *fx, int *fy)
{
    if (z == ZOOM_WORLD) { *fx = (ax - FIT_X) * WORLD_W / FIT_W; *fy = ay * WORLD_H / FIT_H; return; }
    *fx = wm.ox + ax * scale(z);
    *fy = wm.oy + ay * scale(z);
}
/** Changes the zoom by STEP (+1 out, -1 in), keeping the world point under viewport point (AX, AY). */
static void zoom(int step, int ax, int ay)
{
    int to = wm.zoom + step, fx, fy;
    if (to < ZOOM_FULL || to > ZOOM_WORLD)
        return;
    to_full(wm.zoom, ax, ay, &fx, &fy);
    wm.zoom = to;
    if (to != ZOOM_WORLD) {
        wm.ox = fx - ax * scale(to);
        wm.oy = fy - ay * scale(to);
    }
    clamp();
}

/* ---------------------------------------------------- hooks and input */
void xeen_world_map_pass(int blink, const xeen_archive *assets)
{
    size_t n;
    uint8_t *pal;
    if (!xeen_world_map_on)
        return;
    if (!wm.text.loaded && assets) {             /* the button's font and the capture's palette */
        (void)xeen_text_window_load(&wm.text, assets);
        if ((pal = resource(assets, "mm4.pal", &n)) && n >= 768u)
            memcpy(wm.pal, pal, 768);
        free(pal);
    }
    wm.map_shown = 1;
    wm.blink = blink;
}
void xeen_world_map_closed(void) { wm.map_shown = wm.open = wm.dragging = wm.wheel = wm.pressed = wm.owner = 0; }
