/** The button over the M map: 1871B's frame as its panel, the icon (pressed or not) and its label (reduced font, W in
 *  colour 37). */
static void draw_button(uint8_t *page)
{
    uint16_t panel[4] = {BUTTON_X, BUTTON_Y, BUTTON_W, BUTTON_H};
    unsigned r;
    (void)xeen_text_frame(page, 64000, panel);
    for (r = 0; r < 20u; ++r)
        memcpy(page + (ICON_Y + r) * 320u + ICON_X, wm.pressed ? world_map_icon_pressed[r] : world_map_icon_normal[r], 24);
    text(page, BUTTON_X + 4, ICON_Y + 22, BUTTON_W - 8, 9, "\x02\x03" "c\x0c" "37W\x0c" "dorld Map");
}
/** The red ring (owner, Phase 247: one style for every target, constant size at every zoom) around world cell
 *  (X, Y from the south): radius 7 black, 6 red, 5 black, clipped to the view. */
static void draw_ring(uint8_t *page, int x, int y)
{
    int fx = x * CELL_W + CELL_W / 2, fy = (GRID_ROWS * 16 - 1 - y) * CELL_H + CELL_H / 2, cx, cy, dx, dy, r;
    uint8_t black = nearest(0, 0, 0), red = nearest(63, 0, 0);
    if (wm.zoom == ZOOM_FULL) { cx = fx - wm.ox; cy = fy - wm.oy; }
    else if (wm.zoom == ZOOM_HALF) { cx = (fx - wm.ox) / 2; cy = (fy - wm.oy) / 2; }
    else { cx = FIT_X + fx * FIT_W / WORLD_W; cy = fy * FIT_H / WORLD_H; }
    for (dy = -8; dy <= 8; ++dy)
        for (dx = -8; dx <= 8; ++dx) {
            int d = 4 * (dx * dx + dy * dy), px = cx + dx, py = cy + dy;
            for (r = 5; r <= 7; ++r)
                if (d >= (2 * r - 1) * (2 * r - 1) && d < (2 * r + 1) * (2 * r + 1))
                    break;
            if (r > 7 || px < 0 || py < 0 || px >= VIEW_W || py >= VIEW_H)
                continue;
            page[(VIEW_Y + py) * 320 + VIEW_X + px] = r == 6 ? red : black;
        }
}
/** The world map screen: 1871B's frame over the screen, the viewport, the arrow, 4F6F8's border, the lines. */
static void draw_world(uint8_t *page)
{
    static const char *const dirs[4] = {"North", "East", "South", "West"};
    static const char *const zooms[3] = {"Full size", "Half size", "Whole world"};
    static uint8_t arrow_page[64000];
    uint16_t screen[4] = {0, 0, 320, 200};
    int y, ax, ay;
    char line[160];
    memset(page, 0, 64000);
    (void)xeen_text_frame(page, 64000, screen);
    for (y = 0; y < VIEW_H; ++y) {
        uint8_t *row = page + (VIEW_Y + y) * 320 + VIEW_X;
        if (wm.zoom == ZOOM_FULL) memcpy(row, &wm.full[wm.oy + y][wm.ox], VIEW_W);
        else if (wm.zoom == ZOOM_HALF) memcpy(row, &wm.half[wm.oy / 2 + y][wm.ox / 2], VIEW_W);
        else { memset(row, BACKGROUND, VIEW_W); memcpy(row + FIT_X, wm.fit[y], FIT_W); }
    }
    if (wm.party && wm.blink) {                  /* the arrow (F458 frame ED96 + 1) at its cell, clipped to the view */
        int cy = GRID_ROWS * 16 - 1 - wm.party_y;
        if (wm.zoom == ZOOM_FULL) { ax = wm.party_x * CELL_W - wm.ox; ay = cy * CELL_H - wm.oy; }
        else if (wm.zoom == ZOOM_HALF) { ax = wm.party_x * 5 - wm.ox / 2 - 2; ay = cy * 4 - wm.oy / 2 - 2; }
        else { ax = FIT_X + wm.party_x * 3 - 3; ay = cy * 5 / 2 - 3; }
        memcpy(arrow_page, page, sizeof arrow_page);
        (void)xeen_raster_frame(wm.arrow, wm.arrow_size, (uint16_t)(wm.party_dir + 1), arrow_page, sizeof arrow_page,
                                (int16_t)(VIEW_X + ax), (int16_t)(VIEW_Y + ay), 0, 0);
        for (y = VIEW_Y; y < VIEW_Y + VIEW_H; ++y)
            memcpy(page + y * 320 + VIEW_X, arrow_page + y * 320 + VIEW_X, VIEW_W);
    }
    if (wm.marked)
        draw_ring(page, wm.mark_x, wm.mark_y);
    (void)xeen_text_border(page, 64000, screen);
    text(page, 8, 8, 304, 10, wm.world ? "\x03" "cDarkside of Xeen" : "\x03" "cClouds of Xeen");
    if (wm.owner == XEEN_WORLD_MAP_OWNER_QUESTS)
        snprintf(line, sizeof line, wm.label[0] ? "\x03" "c%s - %s" : "\x03" "c%s%s", wm.label, zooms[wm.zoom]);
    else if (wm.party)
        snprintf(line, sizeof line, "\x03l\x09" "004X = %d\x03" "c\x09" "000%s  %s\x03r\x09" "000Y = %d", wm.local_x,
                 dirs[wm.party_dir], zooms[wm.zoom], wm.local_y);
    else
        snprintf(line, sizeof line, "\x03" "c%s", zooms[wm.zoom]);
    text(page, 8, 183, 304, 10, line);
}
/** Developer evidence: the shown page as PPM (XEEN_WORLD_MAP_CAPTURE=DIR, at most 200). */
static void capture(const uint8_t *page)
{
    char name[512];
    FILE *f;
    unsigned i;
    if (!wm.capture || wm.captured >= 200u)
        return;
    snprintf(name, sizeof name, "%s/world-map-%04u.ppm", wm.capture, wm.captured++);
    if (!(f = fopen(name, "wb")))
        return;
    fprintf(f, "P6\n320 200\n255\n");
    for (i = 0; i < 64000u; ++i) {
        const uint8_t *p = wm.pal + 3 * page[i];
        uint8_t o[3] = {(uint8_t)(p[0] * 255 / 63), (uint8_t)(p[1] * 255 / 63), (uint8_t)(p[2] * 255 / 63)};
        fwrite(o, 1, 3, f);
    }
    fclose(f);
}
const uint8_t *xeen_world_map_page(const uint8_t *page)
{
    if (!xeen_world_map_on || !page || !(wm.map_shown || (wm.open && wm.owner == XEEN_WORLD_MAP_OWNER_QUESTS)))
        return page;
    if (wm.open)
        draw_world(wm.page);
    else {
        memcpy(wm.page, page, sizeof wm.page);
        if (!wm.text.loaded)
            return page;                         /* the font comes with the first open's resources */
        draw_button(wm.page);
    }
    capture(wm.page);
    return wm.page;
}

/* ------------------------------------------------ the wheel and start */
/* The provider contract: 1 with key 0 is "no key", 0 no keyboard. While the
 * world map is open a notch is its zoom key (PgUp/PgDn codes, at the notch's
 * point); otherwise the wrapped keyboard runs first and notches it leaves
 * are dropped (never kept for a later open). */
static int keyboard(void *user, uint16_t *key)
{
    uint16_t x = 0, y = 0;
    int d;
    (void)user;
    if (wm.open && wm.take && (d = wm.take(wm.take_user, &x, &y)) != 0) {
        wm.wheel = 1; wm.wheel_x = x; wm.wheel_y = y;
        *key = d > 0 ? 0xdeu : 0xdfu;
        return 1;
    }
    if (!wm.inner.keyboard(wm.inner.user, key))
        return 0;
    if (!*key && wm.take)
        while (wm.take(wm.take_user, &x, &y) != 0) {}
    return 1;
}
/** Passes a mouse sample request through to the wrapped provider. */
static int mouse(void *user, xeen_mouse_sample *sample) { (void)user; return wm.inner.mouse(wm.inner.user, sample); }

int xeen_world_map_start(xeen_input_provider *provider, xeen_world_map_take take, void *take_user)
{
    xeen_world_map_stop();
    wm.full = malloc((size_t)WORLD_W * WORLD_H);
    wm.half = malloc((size_t)WORLD_W / 2 * WORLD_H / 2);
    wm.fit = malloc((size_t)FIT_W * FIT_H);
    if (!wm.full || !wm.half || !wm.fit) {
        xeen_world_map_stop();
        return 0;
    }
    if (provider && provider->keyboard && provider->mouse && take) {
        wm.inner = *provider; wm.take = take; wm.take_user = take_user;
        provider->keyboard = keyboard; provider->mouse = mouse; provider->user = NULL;
    }
    wm.capture = getenv("XEEN_WORLD_MAP_CAPTURE");   /* developer evidence only */
    xeen_world_map_on = 1;
    return 1;
}
void xeen_world_map_stop(void)
{
    xeen_world_map_on = 0;
    free(wm.full); free(wm.half); free(wm.fit); free(wm.arrow);
    memset(&wm, 0, sizeof wm);
}
