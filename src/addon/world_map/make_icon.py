STROKE = 31
def line(x0, y0, x1, y1, w=2):
    """The points of a line; w 2 adds the neighbour right of a steep step or below a shallow one."""
    pts, n = [], max(abs(x1 - x0), abs(y1 - y0)) or 1
    for i in range(n + 1):
        x, y = round(x0 + (x1 - x0) * i / n), round(y0 + (y1 - y0) * i / n)
        pts.append((x, y))
        if w == 2:
            pts.append((x + 1, y) if abs(y1 - y0) >= abs(x1 - x0) else (x, y + 1))
    return pts
# The folded map: three panels with a zig-zag top and bottom edge, a dotted route across them.
GLYPH = (line(3, 4, 8, 2, 1) + line(8, 2, 13, 4, 1) + line(13, 4, 18, 2, 1)
         + line(3, 14, 8, 12, 1) + line(8, 12, 13, 14, 1) + line(13, 14, 18, 12, 1)
         + line(3, 4, 3, 14) + line(8, 2, 8, 12) + line(13, 4, 13, 14) + line(17, 2, 17, 12)
         + [(5, 9), (7, 8), (10, 7), (15, 6)])
mask = set(GLYPH)
tile = [list(r) for r in STONE]
for x, y in mask:
    tile[y][x] = STROKE
for x, y in mask:
    for hx, hy in ((x + 1, y), (x, y + 1)):
        if (hx, hy) not in mask and 1 <= hx <= 20 and 1 <= hy <= 16:
            tile[hy][hx] = max(1, STONE[hy][hx] - 9)
def press(n):
    p = [[STROKE] * 24 for _ in range(20)]
    for y in range(1, 18):
        for x in range(1, 23):
            p[y][x] = n[y - 1][x - 1]
    p[18], p[19] = list(n[18]), list(n[19])
    for y in range(18):
        p[y][0] = p[y][23] = STROKE
    return p
def emit(name, t):
    print('static const uint8_t %s[20][24]={' % name)
    for r in t:
        print('    {' + ','.join('0x%02x' % v for v in r) + '},')
    print('};')
print('/* Generated by make_icon.py (add-on world_map, NOT original): the World')
print(' * Map button, palette indices; normal and pressed. Do not edit. */')
emit('world_map_icon_normal', tile)
emit('world_map_icon_pressed', press(tile))
