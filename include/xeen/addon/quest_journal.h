#ifndef XEEN_ADDON_QUEST_JOURNAL_H
#define XEEN_ADDON_QUEST_JOURNAL_H
#include <stdint.h>
#include "xeen/addon/world_map.h"
/* Owner-approved add-on quest_journal (Phase 247; NOT original XEEN.DAT
 * behavior, off unless --addon quest_journal or wox.cfg [addons]
 * quest_journal = on): the Quests dialog (V, 3E24F) as a journal.
 *
 *   - Quest Items: every row with an item gets a number 1..9 (in the key
 *     colour, in place of the row's bullet). The number or a click on the row
 *     opens a description window over the list (window 1Eh): the item's name,
 *     a text written for the add-on from the original scripts (owner-approved;
 *     two texts for 34 items: before and after their quest is taken, chosen by
 *     the quest's bit F06F), and "Press space to close" (white, centred).
 *     Space or a click inside the window closes it; Esc closes it and the
 *     dialog; I, Q, A close it and show that list; every other key and click
 *     does nothing while it is open.
 *   - Current Quests and Auto Notes, only while add-on world_map is on too:
 *     the rows with a place get numbers; the number or a click opens the
 *     world map (xeen/addon/world_map.h) with a red ring on the place (a quest:
 *     the NPC you report back to, the cell its text names; a note: its cell,
 *     or the place it is about; a place inside a town or dungeon: its
 *     entrance), zoomed to show the party and the ring (100 %, 50 % or the
 *     whole world), the place's name on the bottom line; a place on the other
 *     side of Xeen shows that side's map. Esc closes the world map back to the
 *     list. Notes without a place (riddles, rhymes; the Mine and Deep
 *     Mine notes: owner) get no number. Without
 *     world_map these two lists are the original's: no numbers, no clicks.
 *
 * Host-only: the dialog runs unchanged; its poll's answers that the add-on
 * takes (the numbers while they select a row, a click on a numbered row,
 * everything while its window or the world map is open) never reach the
 * dialog; the numbers and the window are drawn on a copy of the displayed
 * page. DS, the framebuffer and saves are never written. It depends on no
 * bug fix; the map part uses world_map when that add-on is on.
 *
 * Code: src/addon/quest_journal/ (quest_journal.c the module,
 * quests_modal.inc the dialog's part included by the game, descriptions.inc
 * and targets.inc generated by tools/make_tables.py, a developer step). */

/* Nonzero while the add-on is on (xeen_quest_journal_start). */
extern int xeen_quest_journal_on;
/* Turns the add-on on with the font of SPRITE_ARCHIVES (xeen_sprite_archives);
 * 0 (off) when there is none. */
int xeen_quest_journal_start(const void *sprite_archives);
void xeen_quest_journal_stop(void);

/* Hooks of the Quests dialog (quests_modal.inc). */
/* A list was drawn: MODE 0 items, 1 quests, 2 notes; FORMAT its DS layout
 * text (DS:703A, 70D8 or 7113); ROWS the N (9 or 3) shown entries and IDS
 * their item, quest or note number (-1 for a heading or an empty row); MAPS
 * nonzero while the world map can be opened. */
void xeen_quest_journal_listed(int mode, const char *format, const char *const *rows,
                               const int *ids, unsigned n, int maps);
/* The dialog closed. */
void xeen_quest_journal_ended(void);
/* The row an answer selects: digit KEY 1..9, or a CLICK at (PX, PY) on a
 * numbered row; its number (item, quest or note) or -1. */
int xeen_quest_journal_pick(uint16_t key, int click, uint16_t px, uint16_t py);
/* The description window of quest item ITEM (NAME its list name; DS the
 * game's, read for the quest bit). 0 when ITEM has no text. */
int xeen_quest_journal_open_item(unsigned item, const char *name, const uint8_t *ds);
int xeen_quest_journal_item_open(void);
void xeen_quest_journal_close_item(void);
/* (PX, PY) is inside the description window. */
int xeen_quest_journal_in_window(uint16_t px, uint16_t py);
/* Quest (MODE 1) or note (MODE 2) ID's place: *MARK and its *LABEL; 0 for
 * none. */
int xeen_quest_journal_target(int mode, unsigned id, xeen_world_map_place *mark,
                              const char **label);
/* The page to show instead of PAGE: PAGE itself while nothing is drawn,
 * otherwise a copy with the numbered list or the description window. */
const uint8_t *xeen_quest_journal_page(const uint8_t *page);
#endif
