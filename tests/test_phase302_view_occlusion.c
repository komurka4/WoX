static xeen_movement m;

static void put_in_cell(uint16_t entity, unsigned cell)
{
    unsigned f = m.ds[XEEN_DS_PARTY_DIRECTION];
    m.ds[entity] = (uint8_t)(m.ds[XEEN_DS_PARTY_X] + m.ds[XEEN_DS_STEP_X(f, cell + 2u)]);
    m.ds[(uint16_t)(entity + 1u)] = (uint8_t)(m.ds[XEEN_DS_PARTY_Y] + m.ds[XEEN_DS_STEP_Y(f, cell + 2u)]);
}
static unsigned scene_bits(unsigned n, const occlusion_case *c)
{
    static const uint8_t db[XEEN_MONSTER_RECORD_BYTES];
    unsigned r, k, rest = c->code, bits = 0, views = 0;
    for (r = 0; reads[r].cell != c->cell; r++) {
    }
    memset(&m, 0, sizeof m);
    memcpy(m.ds, xeen_program_ds_image, XEEN_PROGRAM_DS_SIZE);
    m.ds[XEEN_DS_WORLD] = 0;
    m.ds[XEEN_DS_PARTY_DIRECTION] = (uint8_t)(n % 4u);
    m.ds[XEEN_DS_PARTY_X] = 8;
    m.ds[XEEN_DS_PARTY_Y] = 8;
    for (k = 3; k < 170; k++) {
        xeen_write16(&m, (uint16_t)(XEEN_DS_INDOOR_VIEW_RECORD(k) + XEEN_VIEW_RECORD_FRAME), XEEN_VIEW_RECORD_UNUSED);
    }
    for (k = 0; k < reads[r].count; k++) {
        unsigned base = c->constructed && k >= 2 ? 4u : 2u;
        m.ds[XEEN_DS_VIEW_WALL(reads[r].walls[k])] = (uint8_t)(rest % base);
        rest /= base;
    }
    m.ds[XEEN_DS_MAP_MONSTER_COUNT] = m.ds[XEEN_DS_MAP_OBJECT_COUNT] = m.ds[XEEN_DS_WALL_ITEM_COUNT] = 1;
    put_in_cell(XEEN_MAP_MONSTER(0), c->cell);
    put_in_cell(XEEN_DS_MAP_OBJECTS, c->cell);
    put_in_cell(XEEN_DS_WALL_ITEMS, c->cell);
    m.ds[XEEN_DS_WALL_ITEMS + XEEN_WALL_ITEM_DIRECTION] = m.ds[XEEN_DS_PARTY_DIRECTION];
    if (xeen_scene_monsters(&m, db, sizeof db) != XEEN_OK || xeen_scene_objects(&m) != XEEN_OK ||
        xeen_scene_walls(&m) != XEEN_OK) {
        fprintf(stderr, "phase302 view occlusion: case %u refused\n", n);
        exit(1);
    }
    for (k = 0; k < XEEN_VIEW_MONSTER_SLOTS; k++) {
        bits |= m.ds[XEEN_DS_VIEW_MONSTERS + k] != XEEN_VIEW_NO_MONSTER;
    }
    bits |= (unsigned)(m.ds[XEEN_MAP_MONSTER(0) + XEEN_MAP_MONSTER_ACTIVE] == 1) << 1;
    for (k = 0; k < 12; k++) {
        if (xeen_read16(&m, (uint16_t)(XEEN_DS_INDOOR_VIEW_RECORD(object_records[k]) + XEEN_VIEW_RECORD_FRAME)) !=
            XEEN_VIEW_RECORD_UNUSED) {
            bits |= 4u;
        }
    }
    bits |= (unsigned)(m.ds[XEEN_DS_EVENT_OBJECT] != 0) << 3;
    for (k = 0; k < XEEN_VIEW_WALL_ITEM_SLOTS; k++) {
        views += m.ds[XEEN_DS_VIEW_WALL_ITEMS + k] != XEEN_VIEW_NO_WALL_ITEM;
    }
    return bits | views << 4 | (unsigned)(m.ds[XEEN_DS_PARTY_CELL_WALL_ITEM] != 0) << 7;
}
int main(void)
{
    unsigned n, failures = 0, hidden[30] = {0}, shown[30] = {0}, cells = 0;
    for (n = 0; n < CASES; n++) {
        unsigned got = scene_bits(n, &cases[n]);
        if (got != cases[n].bits) {
            if (failures++ < 10) {
                fprintf(stderr, "phase302 view occlusion: cell %u code %u%s: %02x, the original %02x\n",
                        cases[n].cell, cases[n].code, cases[n].constructed ? " (constructed)" : "", got,
                        cases[n].bits);
            }
        }
        if (!cases[n].constructed) {
            ++*((cases[n].bits & 1u) ? &shown[cases[n].cell] : &hidden[cases[n].cell]);
        }
    }
    /* the table is not vacuous: every cell but the party's is both drawn and hidden somewhere */
    for (n = 0; n < 30; n++) {
        cells += shown[n] != 0 && (hidden[n] != 0 || n == 0);
    }
    if (CASES != 623 || cells != 12) {
        fprintf(stderr, "phase302 view occlusion: table %u cases, %u cells both ways\n", (unsigned)CASES, cells);
        return 1;
    }
    if (failures) {
        fprintf(stderr, "phase302 view occlusion: %u of %u cases differ\n", failures, (unsigned)CASES);
        return 1;
    }
    printf("phase302 view occlusion: %u cases as the original\n", (unsigned)CASES);
    return 0;
}
